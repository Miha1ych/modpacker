/**
 * mods-data.js
 * -----------------------------------------------------------------------
 * Курируемые категории подборок и списки "кандидатов" — модов с Modrinth,
 * из которых на лету собирается итоговый набор под выбранный загрузчик,
 * рендер-ядро и версию игры.
 *
 * Как это работает:
 *   - Мы НЕ храним прямые ссылки на файлы модов и НЕ храним привязку
 *     "мод -> версия -> загрузчик" руками. Вместо этого мы храним только
 *     slug'и модов на Modrinth, а совместимость (есть ли у мода сборка
 *     под нужный загрузчик/версию) проверяется на лету через Modrinth API
 *     прямо в браузере пользователя (см. js/app.js -> resolveOne()).
 *     Это значит, что список не "протухает" при выходе новых версий
 *     Minecraft — просто в подборке появится нужный файл, как только
 *     автор мода его выложит.
 *   - Одна "логическая" позиция (candidate) может ссылаться на НЕСКОЛЬКО
 *     альтернативных slug'ов (поле slugs). Это нужно, например, для пары
 *     Starlight (Fabric) / Starlight (Forge) — по сути один и тот же мод,
 *     но с разными страницами на Modrinth под разные загрузчики.
 *     Резолвер берёт первый slug, у которого нашлась подходящая сборка.
 *
 * Ядро рендера (engines):
 *   Для категории "Оптимизация" пользователь отдельным шагом выбирает
 *   ОДНО ядро рендера — они взаимоисключающие, ставить два в одну сборку
 *   нельзя. Сейчас это Sodium, Rubidium, Embeddium и VulkanMod: Rubidium и
 *   Embeddium — это два независимых форка Sodium под Forge/NeoForge (FML),
 *   Embeddium — активно поддерживаемый преемник Rubidium, но обе карточки
 *   показываются явно (не как скрытый fallback), потому что в некоторых
 *   старых сборках модов всё ещё нужен именно Rubidium. Карточки не
 *   привязаны к конкретному загрузчику жёстко — на Fabric/Quilt Rubidium и
 *   Embeddium просто окажутся недоступны, это решает checkEngineAvailability()
 *   в js/app.js на шаге выбора ядра. Всё, что завязано на конкретное ядро
 *   (например "Sodium Extra"), лежит в engineOptional[engineId], а не в
 *   общем optional.
 *
 * Как добавить новую категорию:
 *   Просто добавьте новый ключ в объект CATEGORIES ниже, по образцу
 *   "optimization". "core" — моды, которые отмечаются галочкой по
 *   умолчанию (рекомендуемые), "optional" — дополнительные, которые
 *   пользователь включает сам. Поле "engines" необязательно — если его
 *   нет, шаг выбора ядра в мастере просто пропускается.
 * -----------------------------------------------------------------------
 */

